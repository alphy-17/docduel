@dataclass
class Invoice:
    doc_id: str
    template: str
    vendor: str
    vendor_lines: list[str]
    tax_id: str
    customer: list[str]
    number: str
    issued: date
    due: date
    currency: str
    tax_name: str
    tax_rate: Decimal
    tax_inclusive: bool
    items: list[tuple[str, Decimal, Decimal, Decimal]]  # desc, qty, unit, amount
    subtotal: Decimal
    discount: Decimal | None
    service: Decimal | None
    tax: Decimal
    total: Decimal
    payment: str | None

    def truth(self) -> ReceiptExtraction:
        return ReceiptExtraction(
            vendor_name=self.vendor,
            document_date=self.issued.isoformat(),
            document_number=self.number,
            currency=self.currency,
            line_items=[
                LineItem(description=d, quantity=float(q), unit_price=float(u), amount=float(a))
                for d, q, u, a in self.items
            ],
            subtotal=float(self.subtotal),
            tax=float(self.tax),
            service_charge=float(self.service) if self.service is not None else None,
            discount=float(self.discount) if self.discount is not None else None,
            total=float(self.total),
            payment_method=self.payment.lower() if self.payment else None,
        )


def _money(x: Decimal) -> Decimal:
    return x.quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def make_invoice(template: str, index: int, seed: int = SEED) -> Invoice:
    rng = random.Random(f"{seed}-{template}-{index}")
    cur, _, tax_name, rate, tax_label = rng.choices(CURRENCIES, weights=[c[1] for c in CURRENCIES])[
        0
    ]
    suffix = rng.choice(SUFFIX[cur])
    vendor = f"{rng.choice(NAME_A)} {rng.choice(NAME_B)}" + (f" {suffix}" if suffix else "")
    street = f"{rng.randint(1, 250)} {rng.choice(STREETS)}"
    vendor_lines = [street, rng.choice(CITIES[cur])]
    tax_id = (
        " ".join(str(rng.randint(10, 99)) for _ in range(2))
        + " "
        + " ".join(str(rng.randint(100, 999)) for _ in range(3))
    )
    customer = [
        f"{rng.choice(NAME_A)} {rng.choice(CUSTOMER_TYPES)}",
        f"{rng.randint(1, 300)} {rng.choice(STREETS)}",
        rng.choice(CITIES[cur]),
    ]
    prefix = rng.choice(["INV-", "INV", "TI-", "", "A", "S"])
    number = f"{prefix}{rng.randint(1000, 99999)}"
    issued = date(2025, 1, 1) + timedelta(days=rng.randint(0, 600))
    due = issued + timedelta(days=rng.choice([7, 14, 30]))
    items = []
    for desc, lo, hi in rng.sample(CATALOGUE, rng.randint(1, 6)):
        qty = Decimal(rng.choice([1, 1, 1, 2, 2, 3, 4, 5, 10]))
        unit = _money(Decimal(str(rng.uniform(lo, hi))))
        items.append((desc, qty, unit, _money(qty * unit)))
    subtotal = sum((a for *_, a in items), Decimal("0"))
    discount = (
        _money(subtotal * Decimal(rng.choice(["0.05", "0.10"]))) if rng.random() < 0.2 else None
    )
    service = _money(subtotal * Decimal("0.10")) if template == "C" and rng.random() < 0.3 else None
    base = subtotal - (discount or 0) + (service or 0)
    tax_inclusive = cur in ("AUD", "NZD") and rng.random() < 0.4
    if tax_inclusive:
        tax = _money(base * rate / (1 + rate))
        total = base
    else:
        tax = _money(base * rate)
        total = base + tax
    payment = rng.choice(PAYMENTS) if rng.random() < 0.6 else None
    return Invoice(
        doc_id=f"inv_{template}_{index:04d}",
        template=template,
        vendor=vendor,
        vendor_lines=vendor_lines,
        tax_id=f"{tax_label} {tax_id}",
        customer=customer,
        number=number,
        issued=issued,
        due=due,
        currency=cur,
        tax_name=tax_name,
        tax_rate=rate,
        tax_inclusive=tax_inclusive,
        items=items,
        subtotal=subtotal,
        discount=discount,
        service=service,
        tax=tax,
        total=total,
        payment=payment,
    )


# ---------------------------------------------------------------- rendering


def _fmt(inv: Invoice, x: Decimal, style: str = "symbol") -> str:
    s = f"{x:,.2f}"
    if style == "symbol":
        return f"{SYMBOL[inv.currency]}{s}"
    if style == "code":
        return f"{inv.currency} {s}"
    return s


def _date(d: date, style: str) -> str:
    return {
        "dmy": d.strftime("%d/%m/%Y"),
        "long": f"{d.day} {d.strftime('%b %Y')}",
        "iso": d.isoformat(),
        "us": d.strftime("%B ") + f"{d.day}, {d.year}",
        "short": d.strftime("%d-%b-%y"),
        "mdy": d.strftime("%m/%d/%Y"),
    }[style]


def _qty(q: Decimal) -> str:
    return str(int(q)) if q == q.to_integral() else str(q)


def _pdf(fmt="A4", orientation="P"):
    from fpdf import FPDF

    pdf = FPDF(orientation=orientation, unit="mm", format=fmt)
    pdf.set_creation_date(FIXED_PDF_DATE)
    pdf.set_auto_page_break(True, margin=12)
    pdf.add_page()
    return pdf


def _tax_label(inv: Invoice) -> str:
    pct = f"{int(inv.tax_rate * 100)}%"
    return f"{inv.tax_name} included ({pct})" if inv.tax_inclusive else f"{inv.tax_name} ({pct})"


def _totals_rows(inv: Invoice, money) -> list[tuple[str, str]]:
    rows = [("Subtotal", money(inv.subtotal))]
    if inv.discount is not None:
        rows.append(("Discount", "-" + money(inv.discount)))
    if inv.service is not None:
        rows.append(("Service charge (10%)", money(inv.service)))
    rows.append((_tax_label(inv), money(inv.tax)))
    rows.append(("TOTAL", money(inv.total)))
    return rows


def render_a(inv: Invoice) -> bytes:  # classic bordered table
    pdf = _pdf()
    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(110, 10, inv.vendor)
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, "TAX INVOICE", align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", size=9)
    for line in [*inv.vendor_lines, inv.tax_id]:
        pdf.cell(0, 5, line, new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)
    y = pdf.get_y()
    pdf.set_font("Helvetica", "B", 9)
    pdf.cell(0, 5, "Bill to:", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", size=9)
    for line in inv.customer:
        pdf.cell(0, 5, line, new_x="LMARGIN", new_y="NEXT")
    pdf.set_xy(120, y)
    for k, v in [
        ("Invoice No:", inv.number),
        ("Date:", _date(inv.issued, "dmy")),
        ("Due date:", _date(inv.due, "dmy")),
    ]:
        pdf.set_x(120)
        pdf.cell(30, 5, k)
        pdf.cell(0, 5, v, new_x="LMARGIN", new_y="NEXT")
    pdf.set_y(max(pdf.get_y(), y + 22))
    pdf.ln(4)
    widths = (95, 20, 35, 35)
    pdf.set_font("Helvetica", "B", 9)
    for w, h in zip(widths, ["Description", "Qty", "Unit Price", "Amount"], strict=True):
        pdf.cell(w, 7, h, border=1, align="C")
    pdf.ln()
    pdf.set_font("Helvetica", size=9)
    m = lambda x: _fmt(inv, x)  # noqa: E731
    for d, q, u, a in inv.items:
        pdf.cell(95, 7, d, border=1)
        pdf.cell(20, 7, _qty(q), border=1, align="C")
        pdf.cell(35, 7, m(u), border=1, align="R")
        pdf.cell(35, 7, m(a), border=1, align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(3)
    for k, v in _totals_rows(inv, m):
        pdf.set_font("Helvetica", "B" if k == "TOTAL" else "", 9)
        pdf.set_x(115)
        pdf.cell(40, 6, k)
        pdf.cell(35, 6, v, align="R", new_x="LMARGIN", new_y="NEXT")
    if inv.payment:
        pdf.ln(4)
        pdf.cell(0, 5, f"Payment method: {inv.payment}")
    return bytes(pdf.output())


